/*
 * build-seo.cjs: writes the machine-readable front door.
 *
 *   node build-seo.cjs
 *
 * This material is meant to be found and reused, by people and by the crawlers that
 * answer people's questions. That needs four things, and all four are GENERATED here
 * rather than typed, for the same reason every figure on the site is read out of the
 * data files at load time: a distance hand-copied into a meta tag is a distance that
 * drifts the first time the sheet moves, and nothing would fail.
 *
 *   robots.txt    every crawler allowed, the AI ones named explicitly, sitemap declared
 *   sitemap.xml   the two pages and the six data files, so the JSON is crawlable too
 *   llms.txt      the llmstxt.org convention: one markdown page describing the whole set
 *   JSON-LD       schema.org graphs injected into index.html and booklet.html
 *
 * The JSON-LD is INJECTED, not fetched. index.html and booklet.html build their own
 * figures from template.json at load time, which is right for a reader with a browser
 * and useless to a crawler that does not run scripts. So the numbers are baked into a
 * <script type="application/ld+json"> block between markers, and this script is what
 * puts them there. Re-running is idempotent: the markers are replaced, not appended.
 *
 * Run it after build-template.cjs or build-route.cjs. `node --test` fails if the
 * injected figures no longer match the data files, so a stale block cannot ship.
 */

const fs = require('fs');

const BASE = 'https://thegreatindiaride.prasanthsasikumar.com';
const AUTHOR = 'Prasanth Sasikumar';
const AUTHOR_URL = 'https://prasanthsasikumar.com';

const BEGIN = '<!-- BEGIN ld+json: generated by build-seo.cjs, do not edit by hand -->';
const END = '<!-- END ld+json -->';

// Named rather than left to the wildcard. A bare `User-agent: *` does allow all of
// these, but several of these operators publish their token precisely so a site can
// state a position, and "allowed, deliberately" is a different statement from "never
