function read(p) { return JSON.parse(fs.readFileSync(p, 'utf8')); }
function fmt(n) { return n.toLocaleString('en-IN'); }

/* ─── robots.txt ─────────────────────────────────────────────────────────── */

function robots() {
  const lines = [
    '# Everything here is published to be read, quoted and reused, by people and by',
    '# machines. Attribution is asked for and not enforced; the research plates under',
    '# /media/research/ are other riders\' photographs and are credited per image, so',
    '# those carry somebody else\'s rights and not ours.',
    '#',
    '# See /llms.txt for what this site is and which file holds what.',
    '',
    'User-agent: *',
    'Allow: /',
    '',
  ];
  AI_AGENTS.forEach(function (a) {
    lines.push('User-agent: ' + a);
    lines.push('Allow: /');
    lines.push('');
  });
  lines.push('Sitemap: ' + BASE + '/sitemap.xml');
  lines.push('');
  return lines.join('\n');
}

/* ─── sitemap.xml ────────────────────────────────────────────────────────── */

function sitemap(day) {
  const urls = [
    [BASE + '/', '1.0'],
    [BASE + '/booklet.html', '0.9'],
    [BASE + '/llms.txt', '0.5'],
  ];
  // The data files are listed too. A sitemap is usually pages only, but here the JSON
  // IS the deliverable: someone forking the loop wants template.json, not a screenshot
  // of it, and a crawler that never sees the file cannot tell anyone it exists.
  DATA_FILES.forEach(function (f) { urls.push([BASE + '/' + f[0], '0.6']); });

  const out = ['<?xml version="1.0" encoding="UTF-8"?>',
    '<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">'];
  urls.forEach(function (u) {
    out.push('  <url>');
    out.push('    <loc>' + u[0] + '</loc>');
    out.push('    <lastmod>' + day + '</lastmod>');
    out.push('    <priority>' + u[1] + '</priority>');
    out.push('  </url>');
  });
  out.push('</urlset>');
  out.push('');
  return out.join('\n');
}

