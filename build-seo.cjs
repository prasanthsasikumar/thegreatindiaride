// booklet.html's own predicate, verbatim: a note is unwritten if it is empty or starts
// with TO WRITE. Counted here rather than stated, so the number in llms.txt moves when
// somebody actually writes one.
//
// This counts DISTINCT unwritten notes (10 today: five seasons, four permits, and the
// planned-versus-ridden note), not the 15 dashed boxes the book prints. The book prints
// each unwritten season twice, once on its sector spread and once in the calendar, and
// test/booklet.test.cjs pins that 15 because it is asserting against the rendering. A
// crawler summarising this material wants to know how much guidance is missing, not how
// many times the page admits it.
function countGaps(notes) {
  const written = function (s) { return !!s && String(s).indexOf('TO WRITE') !== 0; };
  const sectors = notes.sectors || {};
  let n = 0;
  Object.keys(sectors).forEach(function (id) {
    if (!written(sectors[id].season)) n++;
    if (!written(sectors[id].permits)) n++;
  });
  if (!written(notes.plannedVsRidden)) n++;
  if (!written(notes.sourcing)) n++;
  return n;
}

/* ─── JSON-LD ────────────────────────────────────────────────────────────── */

function person() {
  return {
    '@type': 'Person',
    '@id': BASE + '/#author',
    name: AUTHOR,
    url: AUTHOR_URL,
    sameAs: ['https://www.instagram.com/thegreatindiaride/'],
  };
}

// One TouristTrip for the loop, with its sectors as the itinerary. This is the entity
// the whole site is about, so both pages point at the same @id rather than each
// describing a trip of its own.
function trip(tpl, route) {
  const t = tpl.totals;
  return {
    '@type': 'TouristTrip',
    '@id': BASE + '/#loop',
    name: 'The Great India Ride: a pan-India motorcycle loop',
    description: 'A ' + fmt(t.km) + ' km motorcycle loop of India in ' + t.sectors +
      ' sectors, drawn as a reusable route template. ' + t.hops + ' hops across ' +
      t.countries + ' countries, ridden over ' + route.nights + ' nights.',
    url: BASE + '/',
    author: { '@id': BASE + '/#author' },
    provider: { '@id': BASE + '/#author' },
    touristType: ['Motorcycle touring', 'Adventure motorcycling', 'Long-distance riding'],
    distance: { '@type': 'Distance', name: fmt(t.km) + ' km' },
    subjectOf: { '@id': BASE + '/booklet.html#routebook' },
    itinerary: {
      '@type': 'ItemList',
      numberOfItems: tpl.sectors.length,
      itemListElement: tpl.sectors.map(function (s, i) {
        return {
          '@type': 'ListItem',
          position: i + 1,
          item: {
            '@type': 'TouristTrip',
            name: s.id + ': ' + s.title,
            description: s.from + ' to ' + s.to + ', ' + fmt(s.km) + ' km and ' +
              Math.round(s.hours) + ' riding hours.',
            distance: { '@type': 'Distance', name: fmt(s.km) + ' km' },
            itinerary: [
              { '@type': 'Place', name: s.from },
              { '@type': 'Place', name: s.to },
            ],
          },
        };
      }),
    },
  };
}

// The JSON files, described as a Dataset with one DataDownload per file. This is the
// part that makes the material fetchable rather than merely readable: a crawler that
// understands schema.org gets the URL, the MIME type and a sentence about each file.
function dataset(tpl) {
  const t = tpl.totals;
  return {
    '@type': 'Dataset',
    '@id': BASE + '/#dataset',
    name: 'Pan-India motorcycle route template and ride record',
    description: 'Machine-readable route data for a ' + fmt(t.km) + ' km motorcycle ' +
      'loop of India, Nepal and Bhutan: ' + t.waypoints + ' waypoints with coordinates, ' +
      t.hops + ' hops with distance and riding hours, the sectors they divide into, the ' +
      'nights and spend of the ride that was actually run, and transcribed field ' +
      'research from the xBhp forum archive.',
    url: BASE + '/',
    license: 'https://github.com/prasanthsasikumar/thegreatindiaride',
    creator: { '@id': BASE + '/#author' },
    isAccessibleForFree: true,
    keywords: [
      'motorcycle touring India', 'pan-India ride', 'all India motorcycle trip',
      'route template', 'Kanyakumari to Kashmir', 'K2K', 'Ladakh',
      'Northeast India Inner Line Permit', 'GPS waypoints', 'itinerary',
    ],
    spatialCoverage: [
      { '@type': 'Place', name: 'India' },
      { '@type': 'Place', name: 'Nepal' },
      { '@type': 'Place', name: 'Bhutan' },
    ],
    distribution: DATA_FILES.map(function (f) {
      return {
        '@type': 'DataDownload',
        name: f[0],
        description: f[1],
        contentUrl: BASE + '/' + f[0],
        encodingFormat: 'application/json',
      };
    }),
  };
}

function indexGraph(tpl, route) {
  return {
    '@context': 'https://schema.org',
    '@graph': [
      {
        '@type': 'WebSite',
        '@id': BASE + '/#website',
        url: BASE + '/',
        name: 'The Great India Ride',
        description: '100 days and ' + fmt(tpl.totals.km) + ' km around India on one ' +
          'motorcycle, told in the order it happened and published as a route template ' +
          'anyone can fork.',
        inLanguage: 'en',
        publisher: { '@id': BASE + '/#author' },
      },
      person(),
      trip(tpl, route),
      dataset(tpl),
    ],
  };
}

function bookletGraph(tpl, route, notes) {
  return {
    '@context': 'https://schema.org',
    '@graph': [
      {
        '@type': 'TechArticle',
        '@id': BASE + '/booklet.html#routebook',
        url: BASE + '/booklet.html',
        headline: 'The route book for the pan-India loop',
        description: 'A printable route book for a ' + fmt(tpl.totals.km) + ' km ' +
          'pan-India motorcycle loop: sector maps, waypoint tables with coordinates ' +
          'and riding hours, a cost projection derived from the ride that was run, a ' +
          'season and permit calendar, blank planning pages, and a field research ' +
          'appendix from the xBhp archive.',
        inLanguage: 'en',
        author: { '@id': BASE + '/#author' },
        about: { '@id': BASE + '/#loop' },
        isBasedOn: { '@id': BASE + '/#dataset' },
        // Stated because the book states it to its reader, in a dashed box on the page.
        // A crawler summarising this material should be able to see the same hole.
        disambiguatingDescription: countGaps(notes) + ' guidance entries (riding ' +
          'seasons and some permit notes) are unwritten and appear on the page as an ' +
          'explicit gap rather than as filler.',
      },
      person(),
      trip(tpl, route),
      dataset(tpl),
    ],
  };
}

/* ─── injection ──────────────────────────────────────────────────────────── */

function inject(file, graph) {
  const html = fs.readFileSync(file, 'utf8');
  const block = BEGIN + '\n<script type="application/ld+json">\n' +
    JSON.stringify(graph, null, 1) + '\n</script>\n' + END;

  const i = html.indexOf(BEGIN);
  const j = html.indexOf(END);
  let out;
  if (i !== -1 && j !== -1) {
    out = html.slice(0, i) + block + html.slice(j + END.length);
  } else {
    // First run: land it just before the stylesheet, which is where the rest of the
    // head's metadata already is.
    const anchor = '<style>';
    const k = html.indexOf(anchor);
    if (k === -1) throw new Error(file + ': no <style> to anchor the block to');
    out = html.slice(0, k) + block + '\n' + html.slice(k);
  }
  fs.writeFileSync(file, out);
  console.log(file + ': ld+json ' + (i === -1 ? 'inserted' : 'refreshed') +
    ' (' + JSON.stringify(graph).length + ' bytes)');
}

/* ─── main ───────────────────────────────────────────────────────────────── */

function main() {
  const tpl = read('template.json');
  const route = read('route.json');
  const notes = read('template-notes.json');
  const research = read('research.json');

  const day = new Date().toISOString().slice(0, 10);

  fs.writeFileSync('robots.txt', robots());
  console.log('robots.txt: ' + AI_AGENTS.length + ' agents named, sitemap declared');

  fs.writeFileSync('sitemap.xml', sitemap(day));
  console.log('sitemap.xml: ' + (3 + DATA_FILES.length) + ' urls');

  fs.writeFileSync('llms.txt', llms(tpl, route, notes, research));
  console.log('llms.txt: written');

  inject('index.html', indexGraph(tpl, route));
  inject('booklet.html', bookletGraph(tpl, route, notes));
}

if (require.main === module) main();

module.exports = {
  BASE, DATA_FILES, AI_AGENTS, BEGIN, END,
  robots, sitemap, llms, indexGraph, bookletGraph, countGaps,
};
